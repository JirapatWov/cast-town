// Helpers on other models. omp's task tool spawns agents by name, and an agent's model belongs to its definition (the
// task tool can't pick one per spawn), so RLT writes one agent per connected model — `rlt-<model id>`, a general worker
// like omp's bundled `task` agent that sends no helpers of its own — into an extension root under its data dir
// (`<dataDir>/omp-ext/agents/*.md`) and starts every omp on a connected model with `--extension <root>`: omp discovers
// `<root>/agents/*.md` for each extension root (pi-coding-agent task/discovery.ts). The root holds no module, so omp loads
// no extension code from it. Only connected models get a helper — omp quietly runs a helper whose model has no
// credentials on the parent's model. The files are rewritten whenever the connected models change; omp reads them again
// at every spawn, so a helper of a model signed out of can't start any more (its name is unknown then).
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { splitSelector } from './models';
import { log } from './util';

export interface HelperAgent {
  name: string; // omp agent name, e.g. "rlt-claude-opus-5-5"
  model: string; // the selector omp reaches the model by (a sign-in channel may differ from the catalog's provider)
  label: string; // "Claude Opus 5.5"
}

/** omp's built-in tools a helper gets: what the bundled `task` agent gets (all of them) minus `task` — helpers don't send
 *  helpers — and minus `learn` / `manage_skill`, which omp gives agents below the top level only with an explicit list.
 *  omp drops the ones that aren't available (`wait` comes along with `bash`). */
export const HELPER_TOOLS = [
  'read', 'bash', 'edit', 'write', 'grep', 'glob', 'find', 'ast_grep', 'ast_edit', 'lsp', 'eval', 'web_search', 'github', 'todo',
  'ask', 'debug', 'ida', 'checkpoint', 'rewind', 'context_notes', 'new_context', 'security_scan', 'memory_edit', 'retain', 'recall', 'reflect',
];

const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 56);

/** One helper per connected model, named after its model id (`rlt-<provider>-<id>` when two providers share an id). */
export function helperAgents(models: { id: string; selector: string; label: string }[]): HelperAgent[] {
  const out: HelperAgent[] = [];
  for (const m of models) {
    const { provider, id } = splitSelector(m.id);
    let name = `rlt-${slug(id) || 'model'}`;
    if (out.some((h) => h.name === name)) name = `rlt-${slug(`${provider}-${id}`)}`;
    if (out.some((h) => h.name === name || h.model === m.selector)) continue;
    out.push({ name, model: m.selector, label: m.label });
  }
  return out;
}

const yamlString = (s: string) => JSON.stringify(s); // JSON strings are valid YAML scalars

/** The agent file: frontmatter like the bundled `task` agent's (auto thinking, no `blocking` — it runs in the background
 *  like `task` does), with the model and the tool list set. */
export function renderHelperAgent(h: HelperAgent): string {
  return [
    '---',
    `name: ${yamlString(h.name)}`,
    `description: ${yamlString(`Helper on ${h.label} (${h.model}): a general worker like \`task\`, with full tools but no helpers of its own.`)}`,
    `model: ${yamlString(h.model)}`,
    'thinking-level: "auto"',
    `tools: ${yamlString(HELPER_TOOLS.join(', '))}`,
    '---',
    `Worker agent for delegated tasks, running on ${h.label}. Generated by CAST — do not edit (it is rewritten).`,
    '',
    'Tools: full access (edit, write, bash, grep, read, …) except sending helpers of your own; use them as needed to finish the task.',
    'Stay on the assigned task; never drift from it.',
    '',
    '- Finish the assigned work only; return the minimum useful result; do not repeat file writes.',
    '- Edit files, run commands and create files when the task needs it.',
    '- Be concise: no filler, no repetition, no tool transcripts. The user cannot see you; your result is notes for whoever sent you.',
    '- Avoid reading whole files unless needed; prefer editing existing files over creating new ones.',
    '- Never create documentation files (*.md) unless asked.',
    '',
  ].join('\n');
}

/** Write `<dataDir>/omp-ext/agents/<name>.md` for every helper and remove RLT's helpers that are no longer wanted.
 *  Files that don't change are not rewritten. Returns the extension root (the path stays the same). */
export function writeHelperAgents(dataDir: string, helpers: HelperAgent[]): string {
  const root = join(dataDir, 'omp-ext');
  const dir = join(root, 'agents');
  mkdirSync(dir, { recursive: true });
  const want = new Map(helpers.map((h) => [`${h.name}.md`, renderHelperAgent(h)]));
  for (const f of readdirSync(dir)) {
    if (f.startsWith('rlt-') && f.endsWith('.md') && !want.has(f)) rmSync(join(dir, f), { force: true });
  }
  for (const [f, body] of want) {
    let cur = '';
    try {
      cur = readFileSync(join(dir, f), 'utf8');
    } catch {
      /* new helper */
    }
    if (cur !== body) writeFileSync(join(dir, f), body);
  }
  log('agents', `helpers by model: ${helpers.length ? helpers.map((h) => `${h.name} → ${h.model}`).join(', ') : 'none (no model CAST knows by name is connected)'}`);
  return root;
}
