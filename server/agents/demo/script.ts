// A tiny DSL for scripted demo turns.
//
// A role script is an ordered list of named steps. Each model request in a turn runs the first step that
// has not happened yet; steps that call tools tag their tool-call ids with the step name (rlt_<step>_<n>),
// so on the next request we can see which steps are done and read their results. A step that returns
// only text ends the turn. Returning null from plan() skips the step.
import type { Conversation, ToolCallRecord } from './conversation';

export interface ToolCall {
  name: string;
  args: Record<string, unknown>;
  id?: string; // set by runScript (rlt_<step>_<n>); generated when missing
}

export interface TurnPlan {
  thinking?: string;
  text?: string;
  calls?: ToolCall[];
}

export interface Ctx {
  conv: Conversation;
  cwd: string;
  /** Tool calls made by a given step in this turn. */
  calls(step: string): ToolCallRecord[];
  /** Result text of a step's (first) tool call, '' if the step did not run. */
  result(step: string): string;
  ran(step: string): boolean;
  /** True when the step ran and its tool reported a failure / denial. */
  failed(step: string): boolean;
}

export interface Step {
  name: string;
  plan(ctx: Ctx): TurnPlan | null;
}

/** Does a tool result say the call failed (rejected edit, denied approval, missing file, …)?
 *  Only the first line counts, and file snapshots (`[path#TAG]`, `12:code`) or "Successfully …" never do. */
export function isFailure(result: string | null): boolean {
  const first = (result ?? '').trim().split('\n')[0] ?? '';
  if (!first || /^\[|^\d+:|^Successfully/i.test(first)) return false;
  return /rejected|denied|not found|could not|no match|failed|error|cannot|no such file/i.test(first);
}

export function makeCtx(conv: Conversation): Ctx {
  const by = (step: string) => conv.turn.filter((c) => c.step === step);
  return {
    conv,
    cwd: conv.cwd ?? process.cwd(),
    calls: by,
    result: (step) => by(step).map((c) => c.result ?? '').join('\n'),
    ran: (step) => by(step).length > 0,
    failed: (step) => by(step).some((c) => isFailure(c.result)),
  };
}

// Seeded from the clock: tool-call ids become transcript item ids, which persist across server restarts.
let callSeq = Date.now() % 1_000_000_000;

export function runScript(ctx: Ctx, steps: Step[], fallback = 'Done.'): TurnPlan {
  for (const step of steps) {
    if (ctx.ran(step.name)) continue;
    const plan = step.plan(ctx);
    if (!plan) continue;
    if (plan.calls?.length) {
      // Tag every call with the step name so the next request knows this step happened.
      return { ...plan, calls: plan.calls.map((c) => ({ ...c, id: `rlt_${step.name}_${(++callSeq).toString(36)}` })) };
    }
    return plan;
  }
  return { text: fallback };
}

/** Tool-call ids generated by runScript (the streaming layer reads them). */
export function callId(call: ToolCall, i: number): string {
  return call.id ?? `rlt_call_${i}_${(++callSeq).toString(36)}`;
}

// ── small helpers for writing scripts ──

export const read = (path: string, intent = `read ${path}`): ToolCall => ({ name: 'read', args: { i: intent, path } });
export const write = (path: string, content: string, intent = `write ${path}`): ToolCall => ({ name: 'write', args: { i: intent, path, content } });
export const edit = (input: string, intent = 'apply edit'): ToolCall => ({ name: 'edit', args: { i: intent, input } });
export const bash = (command: string, intent = 'run a command'): ToolCall => ({ name: 'bash', args: { i: intent, command } });
export const grep = (pattern: string, path?: string, intent = `search for ${pattern}`): ToolCall => ({
  name: 'grep',
  args: path ? { i: intent, pattern, path } : { i: intent, pattern },
});

/** Shorten long user asks for thinking text. */
export function gist(s: string, max = 90): string {
  const one = s.replace(/\s+/g, ' ').trim();
  return one.length > max ? `${one.slice(0, max - 1)}…` : one;
}
