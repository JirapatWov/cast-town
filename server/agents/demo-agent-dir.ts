// Generates data/omp-demo-agent/ — the PI_CODING_AGENT_DIR used by demo-mode omp processes.
// It holds a models.yml with one keyless provider, `rlt-demo`, pointing at RLT's local mock LLM and offering
// one model per real model id (rlt-demo/claude-opus-5-5, rlt-demo/gpt-6.1-sol, …) with the real catalog prices,
// so demo runs show realistic token/cost numbers. Nothing in the user's ~/.omp is touched.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { DEMO_PROVIDER, splitSelector, type CatalogModel } from './models';

const yamlString = (s: string) => JSON.stringify(s); // JSON strings are valid YAML scalars

export function renderDemoModelsYml(port: number, models: CatalogModel[]): string {
  const seen = new Set<string>();
  const lines = [
    '# Generated by CAST at startup — do not edit (it is rewritten).',
    '# Keyless stand-ins for real models, served by the local CAST mock LLM.',
    'providers:',
    `  ${DEMO_PROVIDER}:`,
    `    baseUrl: http://127.0.0.1:${port}/v1`,
    '    auth: none',
    '    api: openai-completions',
    '    compat:',
    '      reasoningContentField: reasoning_content',
    '      supportsUsageInStreaming: true',
    '    models:',
  ];
  for (const m of models) {
    const id = splitSelector(m.id).id;
    if (seen.has(id)) continue;
    seen.add(id);
    const c = m.cost;
    lines.push(
      `      - id: ${yamlString(id)}`,
      `        name: ${yamlString(`${m.label} (CAST demo)`)}`,
      `        reasoning: ${m.reasoning ? 'true' : 'false'}`,
      // Like the real model, so demo mode offers (and omp sends) images the same way; the mock ignores image parts.
      `        input: ${m.images ? '[text, image]' : '[text]'}`,
      `        cost: { input: ${c.input}, output: ${c.output}, cacheRead: ${c.cacheRead}, cacheWrite: ${c.cacheWrite} }`,
      `        contextWindow: ${Math.min(m.contextWindow, 400_000)}`,
      `        maxTokens: ${Math.min(m.maxTokens, 32_000)}`,
    );
  }
  return `${lines.join('\n')}\n`;
}

/** Write (or refresh) the demo agent dir. Returns its absolute path. */
export function writeDemoAgentDir(dataDir: string, port: number, models: CatalogModel[]): string {
  const dir = join(dataDir, 'omp-demo-agent');
  mkdirSync(dir, { recursive: true });
  const file = join(dir, 'models.yml');
  const next = renderDemoModelsYml(port, models);
  const prev = existsSync(file) ? readFileSync(file, 'utf8') : '';
  if (prev !== next) writeFileSync(file, next);
  return dir;
}
