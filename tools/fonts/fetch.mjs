// Self-hosted web fonts: downloads the woff2 subsets CAST uses from Google Fonts once, into web/public/fonts, and
// writes web/public/fonts/fonts.css (@font-face with font-display: swap). The app then never talks to Google at run
// time (it must start on an offline LAN, and a local tool should not send every visitor's IP to a third party).
//   node tools/fonts/fetch.mjs        (needs internet; commit the result)
// All three families are SIL Open Font License 1.1 — web/public/fonts/OFL.txt travels with the files.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../web/public/fonts');
// A current desktop Chrome UA: Google answers with woff2 + unicode-range subsets.
const UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36';

/** family query → file prefix, and which unicode subsets to keep (the browser fetches a subset only when a glyph
 *  of its range is on screen, so extra subsets cost disk, not bandwidth). */
const FAMILIES = [
  // Inter is variable: one file per subset covers every weight the CSS uses (400…800, incl. 550/650).
  { query: 'Inter:wght@400..800', prefix: 'inter', subsets: ['latin', 'latin-ext', 'cyrillic', 'cyrillic-ext', 'greek', 'vietnamese'] },
  { query: 'JetBrains+Mono:wght@400..700', prefix: 'jetbrains-mono', subsets: ['latin', 'latin-ext', 'cyrillic', 'greek', 'vietnamese'] },
  // Thai only: Latin text is set in Inter (first in the stack), so Plex's Latin subset would never be used.
  { query: 'IBM+Plex+Sans+Thai:wght@400;500;600', prefix: 'ibm-plex-sans-thai', subsets: ['thai'] },
];

async function text(url) {
  const res = await fetch(url, { headers: { 'user-agent': UA } });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return res.text();
}

const BLOCK = /\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*{([^}]*)}/g;
const prop = (body, name) => new RegExp(`${name}:\\s*([^;]+);`).exec(body)?.[1].trim();

mkdirSync(OUT, { recursive: true });
const faces = [];
const files = new Map(); // remote url → local file name (variable fonts repeat one url per declared weight)
for (const fam of FAMILIES) {
  const css = await text(`https://fonts.googleapis.com/css2?family=${fam.query}&display=swap`);
  for (const [, subset, body] of css.matchAll(BLOCK)) {
    if (!fam.subsets.includes(subset)) continue;
    const family = prop(body, 'font-family');
    const weight = prop(body, 'font-weight');
    const range = prop(body, 'unicode-range');
    const url = /url\((https:[^)]+\.woff2)\)/.exec(body)?.[1];
    if (!family || !weight || !range || !url) throw new Error(`unexpected @font-face for ${fam.query} ${subset}`);
    let name = files.get(url);
    if (!name) {
      const w = weight.includes(' ') ? 'var' : weight;
      name = `${fam.prefix}-${subset}-${w}.woff2`;
      const res = await fetch(url, { headers: { 'user-agent': UA } });
      if (!res.ok) throw new Error(`${res.status} ${url}`);
      writeFileSync(join(OUT, name), new Uint8Array(await res.arrayBuffer()));
      files.set(url, name);
      console.log(`${name}  ${subset}  ${weight}`);
    }
    faces.push(
      `/* ${subset} */\n@font-face {\n  font-family: ${family};\n  font-style: normal;\n  font-weight: ${weight};\n  font-display: swap;\n` +
        `  src: url('/fonts/${name}') format('woff2');\n  unicode-range: ${range};\n}`,
    );
  }
}

const header =
  '/* Generated by tools/fonts/fetch.mjs — self-hosted Inter, JetBrains Mono and IBM Plex Sans Thai (SIL OFL 1.1, see OFL.txt).\n' +
  ' * font-display: swap: text shows at once in the system font and switches when the file arrives. */\n';
writeFileSync(join(OUT, 'fonts.css'), `${header}${faces.join('\n')}\n`);
console.log(`wrote ${faces.length} @font-face rules, ${files.size} files → ${OUT}`);
